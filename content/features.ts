/**
 * 기능 플래그.
 *
 * 왜 환경변수가 아니라 코드 상수인가 —
 *  - 켜고 끄는 판단이 **컴플라이언스 결정**이다. 대시보드에서 조용히 바뀌면 안 되고
 *    PR 로 검토·기록되어야 한다.
 *  - 환경변수는 빌드 시점에 값이 없으면 **켜진 채로 빌드될 수 있다.** 코드 상수는
 *    저장소에 적힌 값이 곧 배포된 값이다.
 *
 * ⚠️ **"`false` 면 트리셰이킹되어 배포물에서 사라진다" 고 적혀 있었으나 사실이 아니다**
 *    (2026-09-14, 측정으로 확인). 타입이 리터럴 `false` 가 아니라 `boolean` 이라
 *    번들러가 분기를 제거하지 못한다 — **모듈 코드는 청크에 그대로 남는다.**
 *    바로 아래 "타입을 `boolean` 으로 명시한 이유" 와 맞바꾼 것이다.
 *    실제로 달라지는 것은 **렌더 여부**다: `analytics` 를 끄면 `<Analytics />` 가
 *    렌더되지 않아 `/_vercel/insights/script.js` 를 **요청하지 않는다**(브라우저
 *    네트워크로 확인). 수집이 멈추는 근거는 트리셰이킹이 아니라 이것이다.
 *    → 플래그를 끈 뒤 "번들에 남아 있으니 아직 도는 것 아니냐" 고 의심하지 말 것.
 *      확인 방법은 `.claude/skills/homepage-verify` 함정 10.
 *  - 재활성화는 이 파일 한 줄 변경이다.
 *
 * ⚠️ 플래그를 켤 때 함께 해야 하는 일이 있다. 각 항목 주석을 반드시 읽을 것.
 *
 * 타입을 `boolean` 으로 명시한 이유: `as const` 로 두면 리터럴 타입 `false` 로 좁혀져
 * **비활성 분기가 죽은 코드가 되고 타입 검사·린트에서 빠진다.** 나중에 켤 코드가
 * 검사받지 못하는 상태로 방치되면 켜는 순간 깨진다.
 */
